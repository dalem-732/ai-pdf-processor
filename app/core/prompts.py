"""Промпты для стадии извлечения фактов.

Промпт спроектирован под одну задачу: превратить фрагмент документации в
строгий JSON без домыслов. Требования, которые реально влияют на качество и
поэтому сформулированы явно:

* отвечать только тем, что есть в тексте (пропуск лучше выдумки - выжимка
  используется для решения об участии в закупке, где цена ошибки - деньги);
* незаполненные поля возвращать как null/[], а не пропускать (иначе схема
  разъезжается и валидация превращается в угадывание);
* цитировать суммы дословно в поле raw (даёт возможность сверить ответ
  модели с текстом регулярками и поймать галлюцинацию);
* указывать номера страниц из маркеров [[стр. N]] (прослеживаемость: пользователь
  должен уметь открыть страницу и проверить).
"""

from __future__ import annotations

SYSTEM_PROMPT = """Ты - аналитик тендерной документации по 44-ФЗ и 223-ФЗ.
Твоя работа - извлекать из фрагментов закупочной документации структурированные
факты и возвращать их строго в формате JSON.

Жёсткие правила:
1. Используй ТОЛЬКО информацию из присланного фрагмента. Ничего не додумывай,
   не подставляй типовые значения из практики закупок и не рассчитывай суммы
   самостоятельно.
2. Если факта во фрагменте нет, верни null для объекта/строки и [] для списка.
3. Суммы указывай числом в поле amount и обязательно приводи дословную цитату
   из текста в поле raw.
4. В source_pages указывай номера страниц из маркеров вида [[стр. 7]],
   в границах которых находится факт.
5. Формулировки требований и штрафов сокращай до одного ёмкого пункта, но не
   меняй их юридический смысл и не обобщай несколько пунктов в один.
6. Требования (`requirements`) - только квалификация и допуск к исполнению:
   лицензии, СРО, опыт, штат, обеспечение заявки/контракта, финансовая
   устойчивость, обязательные документы для допуска. Не включай рутинные
   обязанности подрядчика при выполнении работ (страхование на период работ,
   материалы, охрана труда, видеофиксация, вывоз мусора и т.п.).
7. Штрафы (`penalties`) - только денежные меры: пеня, штраф, неустойка,
   удержание обеспечения с формулой или суммой. Не включай включение в РНП,
   одностороннее расторжение и общие оговорки об ответственности; не включай
   санкции за нарушения заказчика (например, просрочку оплаты).
8. Этапы (`deadlines.stages`) - только этапы выполнения работ/оказания услуг
   (этап 1, этап 2, проектирование, капремонт). Прочие сроки (возврат
   обеспечения, открытие счёта, согласование документов) помещай в
   `deadlines.raw_mentions`, а не в `stages`.
9. Ответ - только JSON-объект без markdown, комментариев и пояснений."""

JSON_SCHEMA_HINT = """{
  "subject": "строка | null - предмет закупки",
  "customer": "строка | null - наименование заказчика",
  "procurement_number": "строка | null - номер извещения на ЕИС (19-20 цифр) или краткий номер закупки",
  "contract_price": {"amount": число, "currency": "RUB", "includes_vat": true/false/null, "raw": "цитата"} | null,
  "contract_security": {"amount": число, "currency": "RUB", "raw": "цитата"} | null,
  "application_security": {"amount": число, "currency": "RUB", "raw": "цитата"} | null,
  "deadlines": {
    "start": "строка | null - дата или условие начала",
    "end": "строка | null - дата или условие окончания",
    "duration": "строка | null - например: 180 календарных дней",
    "stages": [{"name": "название этапа работ", "deadline": "срок этапа | null"}],
    "raw_mentions": ["цитаты из текста о сроках"]
  },
  "requirements": [
    {
      "category": "license|qualification|experience|staff|equipment|financial|documents|other",
      "text": "требование к допуску/квалификации исполнителя (не обязанность при выполнении работ)",
      "mandatory": true/false,
      "source_pages": [номера страниц]
    }
  ],
  "penalties": [
    {
      "violation": "за что наступает ответственность",
      "sanction": "пеня | штраф | неустойка | удержание обеспечения",
      "formula": "порядок расчёта | null",
      "amount": {"amount": число, "currency": "RUB", "raw": "цитата"} | null,
      "source_pages": [номера страниц]
    }
  ]
}"""


def build_extraction_prompt(
    *, chunk_text: str, part_number: int, parts_total: int, pages_label: str
) -> str:
    """Пользовательская часть промпта для одного фрагмента документа."""
    return f"""Фрагмент {part_number} из {parts_total} документа тендерной документации ({pages_label}).

Извлеки из фрагмента факты и верни JSON строго следующей структуры:
{JSON_SCHEMA_HINT}

Извлекай только то, что действительно присутствует в тексте фрагмента ниже.
Особое внимание: сумма (цена) контракта, сроки выполнения, требования к
исполнителю, штрафы и пени.

=== ТЕКСТ ФРАГМЕНТА ===
{chunk_text}
=== КОНЕЦ ФРАГМЕНТА ==="""
